package draw

import "unicode"

func GeneratePatternFromText(text string) []string {
	height := 7
	pattern := make([]string, height)

	for _, ch := range text {
		if font, ok := asciiFont[unicode.ToUpper(ch)]; ok {
			for i := 0; i < height; i++ {
				pattern[i] += font[i] + " "
			}
		}
	}

	return pattern
}

